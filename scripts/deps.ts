// dependency-cruiser on src/:
//   node scripts/deps.ts          writes docs/dependencies.md, the import graph as
//                                 Mermaid diagrams, one per folder and one per file
//   node scripts/deps.ts --check  checks the layering rules of .dependency-cruiser.cjs
//
// dependency-cruiser is run through npx, so it is not a dependency of the
// project. It only runs on even Node versions and only reads TypeScript < 7,
// so npx also fetches Node 24 and TypeScript 5 for this one command.
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';

const OUT = 'docs/dependencies.md';

/** Runs depcruise on src/ and returns its output; throws if it exits with an error. */
function depcruise(...args: string[]): string {
  const npx = ['--yes', '-p', 'node@24', '-p', 'typescript@5', '-p', 'dependency-cruiser@18.6.0', '--'];
  // npx-cli.js next to the npm that runs this script: no shell (npx is npx.cmd on Windows, which would eat the ^)
  const npmCli = process.env['npm_execpath'];
  if (!npmCli) throw new Error('run this with `npm run deps` or `npm run deps:check`');
  const npxCli = join(dirname(npmCli), 'npx-cli.js');
  return execFileSync(process.execPath, [npxCli, ...npx, 'depcruise', 'src', ...args], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
  }).trim();
}

if (process.argv.includes('--check')) {
  try {
    console.log(depcruise('--config', '.dependency-cruiser.cjs', '--output-type', 'err'));
  } catch (error) {
    // the violations are on stdout
    console.error((error as { stdout?: string }).stdout ?? error);
    process.exit(1);
  }
} else {
  const mermaid = (...args: string[]) =>
    depcruise(
      '--no-config',
      '--ts-config',
      'tsconfig.json',
      '--ts-pre-compilation-deps', // also count `import type`
      '--include-only',
      '^src',
      '--output-type',
      'mermaid',
      ...args,
    );
  const folders = mermaid('--collapse', '2');
  const files = mermaid();

  await writeFile(
    OUT,
    `# Dependencies of src/

Generated by \`npm run deps\` (dependency-cruiser), do not edit. An arrow points
from the importing module to the imported one; \`import type\` counts as well.
\`npm run deps:check\` checks the layering rules in \`.dependency-cruiser.cjs\`.

## Folders

\`\`\`mermaid
${folders}
\`\`\`

## Files

\`\`\`mermaid
${files}
\`\`\`
`,
  );
  console.log(`wrote ${OUT}`);
}
